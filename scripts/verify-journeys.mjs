import { chromium } from 'playwright'

const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
const origin = (process.env.MUMU_VERIFY_URL ?? 'http://127.0.0.1:4173').replace(/\/$/, '')
const failures = []
const submissions = []
page.on('pageerror', error => failures.push(`Runtime: ${error.message}`))
page.on('request', request => {
  if (!['GET', 'HEAD'].includes(request.method())) submissions.push(`${request.method()} ${request.url()}`)
})
const check = (condition, label) => { if (!condition) failures.push(label) }
const text = async selector => (await page.locator(selector).textContent())?.trim() ?? ''

await page.goto(`${origin}/`, { waitUntil: 'networkidle' })
await page.evaluate(() => window.scrollTo(0, 650))
await page.waitForTimeout(100)
check(await page.locator('.mobile-order-cta').count() === 1, 'Mobile sticky order action appears after hero')
await page.locator('#footer').scrollIntoViewIfNeeded()
await page.waitForTimeout(100)
check(await page.locator('.mobile-order-cta').count() === 0, 'Mobile sticky order action clears footer')
await page.getByRole('link', { name: /Order Ice/i }).first().click()
check(new URL(page.url()).pathname === '/order', 'Homepage Order Ice link')
check(await page.locator('h2:focus').count() === 0, 'Initial order focus should remain unset')
await page.getByRole('button', { name: 'Continue to delivery' }).click()
check(await page.getByText('Choose an occasion to continue.').count() === 1, 'Order occasion validation')
check(await page.locator('#occasion:focus').count() === 1, 'Order error focus')
await page.getByLabel('Party', { exact: true }).check()
await page.getByRole('button', { name: 'Add one bag' }).click()
await page.getByRole('button', { name: 'Continue to delivery' }).click()
check(await page.locator('h2:focus').count() === 1, 'Stage focus after continue')
await page.getByRole('button', { name: 'Review request' }).click()
check(await page.getByText('Enter the recipient’s full name.').count() === 1, 'Delivery required validation')
await page.getByRole('button', { name: 'Use sample details' }).click()
await page.locator('#date').fill('2020-01-01')
await page.getByRole('button', { name: 'Review request' }).click()
check(await page.getByText('Choose today or a future date in Kampala time.').count() === 1, 'Past delivery date rejected')
await page.getByRole('button', { name: 'Use sample details' }).click()
await page.getByRole('button', { name: 'Review request' }).click()
check((await text('.order-review-grid')).includes('2 bags'), 'Review quantity')
check((await text('.order-review-grid')).includes('Sample House, Demo Street'), 'Review sample address')
await page.getByRole('button', { name: /Edit ice requirements/ }).click()
await page.locator('#quantity').fill('4')
await page.getByRole('button', { name: 'Continue to delivery' }).click()
await page.locator('#address').fill('Revised Demo Street')
await page.getByRole('button', { name: 'Review request' }).click()
check((await text('.order-review-grid')).includes('4 bags'), 'Edited quantity reflected')
check((await text('.order-review-grid')).includes('Revised Demo Street'), 'Edited address reflected')
check((await text('.price-notice')).includes('to be confirmed'), 'Honest price display')
await page.getByRole('button', { name: 'Preview request confirmation' }).click()
check((await text('.confirmation')).includes('No request was submitted'), 'Order local confirmation')
await page.getByRole('button', { name: 'Start a new demo request' }).click()
check(await page.locator('#quantity').inputValue() === '1', 'Order reset quantity')
check(await page.locator('input[name="occasion"]:checked').count() === 0, 'Order reset occasion')

await page.goto(`${origin}/delivery`, { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Add location' }).click()
check(await page.getByText('Enter an area or choose an example location.').count() === 1, 'Area validation')
await page.getByRole('button', { name: /Ntinda/ }).click()
check((await text('.area-result')).includes('Availability and delivery charges would be confirmed by the supplier.'), 'Honest area result')
await page.getByRole('link', { name: /Start a delivery request/ }).first().click()
check(new URL(page.url()).pathname === '/order', 'Delivery to order route')

await page.goto(`${origin}/business`, { waitUntil: 'networkidle' })
await page.getByRole('button', { name: /Parties and private events/ }).click()
check(await page.locator('#business-date').count() === 1 && await page.locator('#guests').count() === 1, 'Event fields revealed')
await page.locator('#business-type').selectOption('Recurring business supply')
check(await page.locator('#bags').count() === 1 && await page.locator('#business-date').count() === 0, 'Supply fields revealed')
await page.getByRole('button', { name: 'Preview enquiry' }).click()
check(await page.getByText('Enter a phone number or an email address.').count() === 1, 'Business contact validation')
await page.locator('#business-name').fill('Sample Person')
await page.locator('#business-email').fill('sample@example.invalid')
await page.locator('#business-location').fill('Example area, Kampala')
await page.locator('#bags').fill('12')
await page.getByRole('button', { name: 'Preview enquiry' }).click()
check((await text('.confirmation')).includes('Nothing was sent'), 'Business local preview')
check((await text('.business-summary')).includes('12'), 'Business preview bag count')
await page.getByRole('button', { name: 'Start again' }).click()
check(await page.locator('#business-name').inputValue() === '', 'Business reset')

await page.goto(`${origin}/contact`, { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Preview message' }).click()
check(await page.getByText('Write a short message.').count() === 1, 'Contact message validation')
await page.locator('#contact-name').fill('Sample Person')
await page.locator('#contact-value').fill('sample@example.invalid')
await page.locator('#topic').selectOption('General question')
await page.locator('#message').fill('This is a fictional question for the local demo.')
await page.getByRole('button', { name: 'Preview message' }).click()
check((await text('.confirmation')).includes('No message was sent'), 'Contact local preview')
await page.getByRole('button', { name: 'Start again' }).click()
check(await page.locator('#contact-name').inputValue() === '', 'Contact reset')

for (const route of ['/', '/order', '/delivery', '/business', '/contact']) {
  for (const width of [360, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: width < 700 ? 800 : 900 })
    const response = await page.goto(`${origin}${route}`, { waitUntil: 'domcontentloaded' })
    await page.reload({ waitUntil: 'domcontentloaded' })
    const dimensions = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth, h1: document.querySelectorAll('h1').length }))
    check(response?.status() === 200, `${route} ${width} direct load`)
    check(dimensions.document <= dimensions.viewport, `${route} ${width} horizontal overflow: ${dimensions.document}`)
    check(dimensions.h1 === 1, `${route} ${width} H1 count`)
  }
}
check(submissions.length === 0, `Unexpected non-GET requests: ${submissions.join(', ')}`)
await browser.close()
if (failures.length) { console.error(failures.join('\n')); process.exit(1) }
console.log('Verified order, delivery, business, contact, resets, direct routes, reduced motion and 20 responsive layouts. No external form submissions.')
